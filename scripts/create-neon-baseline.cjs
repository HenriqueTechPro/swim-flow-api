#!/usr/bin/env node
'use strict';

// Generate or verify the first versioned migration for a NEW EMPTY Postgres DB.
// No database is contacted. Prisma-managed DDL is followed by checked-in SQL.
const { spawnSync } = require('node:child_process');
const { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } = require('node:fs');
const { resolve, join } = require('node:path');
const { createHash } = require('node:crypto');

const root = resolve(__dirname, '..');
const target = join(root, 'prisma/migrations/20261020000000_init_neon/migration.sql');
const inputs = [
  'prisma/schema.prisma',
  'prisma/sql/pre_neon/02c_seasons_enrollments.sql',
  'prisma/sql/pre_neon/02c2_guardians_identity.sql',
  'prisma/sql/pre_neon/02c3_departure_history.sql',
  'prisma/sql/pre_neon/02d_domain_invariants.sql',
];
const check = process.argv.includes('--check');
if (process.argv.slice(2).some((arg) => arg !== '--check')) {
  throw new Error('Usage: node scripts/create-neon-baseline.cjs [--check]');
}
// The baseline is frozen once incremental migrations exist. Do NOT compare
// future schema versions against the initial DDL (that would encourage
// rewriting the already-applied migration and break migration history).
const migrationsDir = join(root, 'prisma/migrations');
const migrationDirs = readdirSync(migrationsDir, { withFileTypes: true })
  .filter((item) => item.isDirectory() && /^\d{14}_/.test(item.name))
  .map((item) => item.name);
if (migrationDirs.length > 1) {
  if (!check) throw new Error('Baseline is immutable; create an incremental Prisma migration');
  // Git blob SHA of the first reviewed baseline, computed from file bytes.
  // This protects the original SQL once later schema revisions appear.
  const expectedBlobSha = 'a400e1c412e875cc33a766939c1dfcb5b8ccb8bb';
  const bytes = readFileSync(target);
  const actualBlobSha = createHash('sha1')
    .update(Buffer.from('blob ' + bytes.length + '\0'))
    .update(bytes)
    .digest('hex');
  if (actualBlobSha !== expectedBlobSha) {
    throw new Error('Historical initial migration has changed; migrations must be append-only');
  }
  console.log('Historical baseline is unchanged; incremental migrations will be deployed separately.');
  process.exit(0);
}
const sources = inputs.map((path) => ({ path, content: readFileSync(join(root, path), 'utf8') }));
const executable = join(root, 'node_modules/prisma/build/index.js');
if (!existsSync(executable)) throw new Error('Run npm ci to install locked Prisma CLI');
const run = spawnSync(process.execPath, [
  executable, 'migrate', 'diff', '--from-empty',
  '--to-schema-datamodel', join(root, 'prisma/schema.prisma'), '--script',
], {
  cwd: root, env: process.env, encoding: 'utf8', maxBuffer: 20 * 1024 * 1024,
});
if (run.error || run.status !== 0) {
  throw new Error('Prisma migration generation failed: ' + (run.stderr || run.error || run.stdout));
}
if (!run.stdout.includes('CREATE TABLE') || !run.stdout.includes('CREATE TYPE')) {
  throw new Error('Refusing unexpected or empty Prisma PostgreSQL diff');
}
const hash = createHash('sha256');
sources.forEach(({ path, content }) => hash.update(path + '\0' + content + '\0'));
const header = [
  '-- Swim Flow: initial migration for an EMPTY PostgreSQL database ONLY.',
  '-- Prisma schema generated by locked Prisma 6; manual CHECK/partial indexes follow.',
  '-- Sources SHA-256: ' + hash.digest('hex'),
  '-- Verify: node scripts/create-neon-baseline.cjs --check',
  '-- NEVER deploy over the legacy Supabase schema.',
  '',
].join('\n');
const manual = sources.slice(1).map(({ path, content }) => [
  '',
  '-- BEGIN manual SQL: ' + path,
  content.trimEnd(),
  '-- END manual SQL: ' + path,
  '',
].join('\n')).join('');
const generated = header + run.stdout.trimEnd() + '\n' + manual;
if (check) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== generated) {
    console.error('Versioned baseline is missing or stale. Generate it and commit migration.sql.');
    process.exitCode = 1;
  } else {
    console.log('Versioned Prisma + custom SQL baseline is up to date.');
  }
} else {
  mkdirSync(resolve(target, '..'), { recursive: true });
  writeFileSync(target, generated, 'utf8');
  console.log('Wrote migration.sql (' + Buffer.byteLength(generated) + ' bytes).');
}
